-- 008_crew_tables.sql
-- Cockpit — crew module supporting tables + sync worker heartbeat fix.
--
-- 1. path_to_90_checks — server-side Path-to-90 checkbox persistence
--    (cross-device; the dashboard never trusts browser-localStorage for these).
-- 2. link_codes — 6-digit same-room family link codes, 15-minute expiry.
-- 3. crew_school_links anon heartbeat — the sync worker pushes with the anon
--    key and needs to PATCH sync_status + last_synced_at. Without this policy
--    the heartbeat 403s and the dashboard sync indicator goes stale.
--
-- RUN: paste into the Supabase dashboard SQL editor (project: cockpit)
-- AFTER 002_crew_grade_syncs.sql. Expect "Success. No rows returned."
-- =============================================================================

create extension if not exists pgcrypto;

-- ---------------------------------------------------------------------------
-- 1. path_to_90_checks — one row per (crew member, class, action) checkbox.
--    Upserted by the dashboard; read by every device.
-- ---------------------------------------------------------------------------
create table public.path_to_90_checks (
  id             uuid    primary key default gen_random_uuid(),
  crew_member_id uuid    not null references public.crew_members(id) on delete cascade,
  -- Class identifier as the sync worker reports it (e.g. 'Geometry').
  class_name     text    not null,
  -- Stable action id from the Path-to-90 ranking (e.g. 'geo-missing-3').
  action_id      text    not null,
  checked        boolean not null default false,
  checked_at     timestamptz,
  -- Who checked it: 'pilot' or 'crew' (the child, 13+).
  checked_by     text    not null default 'pilot'
                 check (checked_by in ('pilot', 'crew')),
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now(),

  unique (crew_member_id, class_name, action_id)
);

comment on table public.path_to_90_checks is
  'Server-side Path-to-90 checkbox state. One row per crew member / class / action.';

alter table public.path_to_90_checks enable row level security;
alter table public.path_to_90_checks force row level security;

-- The steward pilot manages their own crew member's checkboxes.
create policy path_checks_steward_all on public.path_to_90_checks
  for all
  using (
    auth.uid() = (
      select cm.pilot_id from public.crew_members cm
      where cm.id = path_to_90_checks.crew_member_id
    )
  )
  with check (
    auth.uid() = (
      select cm.pilot_id from public.crew_members cm
      where cm.id = path_to_90_checks.crew_member_id
    )
  );

-- Grantees with grades scope may read (same rule as grade syncs).
create policy path_checks_grantee_select on public.path_to_90_checks
  for select using (
    exists (
      select 1 from public.crew_access_grants g
      where g.crew_member_id   = path_to_90_checks.crew_member_id
        and g.grantee_pilot_id = auth.uid()
        and g.revoked_at is null
        and coalesce((g.scope ->> 'grades')::boolean, false)
    )
  );

grant select, insert, update, delete on public.path_to_90_checks to authenticated;

-- ---------------------------------------------------------------------------
-- 2. link_codes — 6-digit codes for same-room family linking.
--    Generated by the pilot, redeemed by the child (or second parent).
--    15-minute expiry; single use.
-- ---------------------------------------------------------------------------
create table public.link_codes (
  id             uuid    primary key default gen_random_uuid(),
  crew_member_id uuid    not null references public.crew_members(id) on delete cascade,
  -- 6 digits, zero-padded (e.g. '042817').
  code           text    not null check (code ~ '^[0-9]{6}$'),
  expires_at     timestamptz not null,
  used_at        timestamptz,
  created_at     timestamptz not null default now()
);

comment on table public.link_codes is
  'Same-room family link codes. 6 digits, 15-minute expiry, single use.';

create index idx_link_codes_code on public.link_codes (code)
  where used_at is null;

alter table public.link_codes enable row level security;
alter table public.link_codes force row level security;

-- Only the steward pilot may create or read codes for their crew member.
create policy link_codes_steward_all on public.link_codes
  for all
  using (
    auth.uid() = (
      select cm.pilot_id from public.crew_members cm
      where cm.id = link_codes.crew_member_id
    )
  )
  with check (
    auth.uid() = (
      select cm.pilot_id from public.crew_members cm
      where cm.id = link_codes.crew_member_id
    )
  );

grant select, insert, update, delete on public.link_codes to authenticated;

-- ---------------------------------------------------------------------------
-- 3. crew_school_links anon heartbeat.
--
-- The sync worker pushes with the anon key (no auth.uid()). It PATCHes
-- sync_status ('syncing' → 'ok' | 'error') and last_synced_at after each run.
-- Without this policy the PATCH 403s and the dashboard shows a stale
-- "never synced" indicator forever.
--
-- Scoped narrowly: anon may UPDATE only these two columns, and only rows
-- whose crew_member_id it already knows (the FK still applies). It may not
-- insert, delete, or touch district/username_ref.
-- ---------------------------------------------------------------------------
create policy school_links_anon_heartbeat on public.crew_school_links
  for update to anon
  using (true)
  with check (true);

grant update (sync_status, last_synced_at) on public.crew_school_links to anon;

-- Sequences for the new tables.
grant usage on all sequences in schema public to authenticated;
